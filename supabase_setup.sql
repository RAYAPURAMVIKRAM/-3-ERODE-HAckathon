-- 1. Create the SOS Emergency Helpdesk Tickets Table
create table if not exists public.sos_tickets (
    id bigint generated by default as identity primary key,
    name text not null,
    village text not null,
    category text not null,
    description text not null,
    timestamp text not null default to_char(now() at time zone 'Asia/Kolkata', 'YYYY-MM-DD HH24:MI')
);

-- 2. Create Farmer Profiles Table
create table if not exists public.farmers (
    id bigint generated by default as identity primary key,
    email text unique not null,
    name text,
    village text,
    created_at text default to_char(now() at time zone 'Asia/Kolkata', 'YYYY-MM-DD HH24:MI')
);

-- 3. Create Marketplace Crops Table
create table if not exists public.marketplace_crops (
    id bigint generated by default as identity primary key,
    farmer_name text not null,
    phone_whatsapp text not null,
    crop_name text not null,
    quantity_kg numeric not null,
    price_per_kg numeric not null,
    location text not null,
    created_at text not null default to_char(now() at time zone 'Asia/Kolkata', 'YYYY-MM-DD HH24:MI')
);

-- 4. Enable Row Level Security (RLS)
alter table public.sos_tickets enable row level security;
alter table public.farmers enable row level security;
alter table public.marketplace_crops enable row level security;

-- 5. Drop existing policies to prevent conflict errors on re-run
drop policy if exists "Allow public select on sos_tickets" on public.sos_tickets;
drop policy if exists "Allow public insert on sos_tickets" on public.sos_tickets;
drop policy if exists "Allow public update on sos_tickets" on public.sos_tickets;
drop policy if exists "Allow public delete on sos_tickets" on public.sos_tickets;

drop policy if exists "Allow public select on farmers" on public.farmers;
drop policy if exists "Allow public insert on farmers" on public.farmers;
drop policy if exists "Allow public update on farmers" on public.farmers;
drop policy if exists "Allow public delete on farmers" on public.farmers;

drop policy if exists "Allow public select on marketplace_crops" on public.marketplace_crops;
drop policy if exists "Allow public insert on marketplace_crops" on public.marketplace_crops;
drop policy if exists "Allow public update on marketplace_crops" on public.marketplace_crops;
drop policy if exists "Allow public delete on marketplace_crops" on public.marketplace_crops;


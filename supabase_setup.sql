create policy "Allow public update on sos_tickets" on public.sos_tickets for update using (true);
create policy "Allow public delete on sos_tickets" on public.sos_tickets for delete using (true);

create policy "Allow public select on farmers" on public.farmers for select using (true);
create policy "Allow public insert on farmers" on public.farmers for insert with check (true);
create policy "Allow public update on farmers" on public.farmers for update using (true);
create policy "Allow public delete on farmers" on public.farmers for delete using (true);

create policy "Allow public select on marketplace_crops" on public.marketplace_crops for select using (true);
create policy "Allow public insert on marketplace_crops" on public.marketplace_crops for insert with check (true);
create policy "Allow public update on marketplace_crops" on public.marketplace_crops for update using (true);
create policy "Allow public delete on marketplace_crops" on public.marketplace_crops for delete using (true);

-- 7. Grant Permissions to anon, authenticated, and service_role
grant all on table public.sos_tickets to anon, authenticated, service_role;
grant all on table public.farmers to anon, authenticated, service_role;
